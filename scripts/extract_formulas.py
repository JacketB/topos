def get_dist(p1, p2):
    cos_lat = math.cos(math.radians((p1[1] + p2[1]) / 2.0))
    dx = (p1[0] - p2[0]) * cos_lat
    dy = p1[1] - p2[1]
    return dx * dx + dy * dy

base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tauri_places = os.path.join(base_dir, "src-tauri", "assets", "belarus_places.json")
public_places = os.path.join(base_dir, "public", "assets", "belarus_places.json")

with open(tauri_places, "r", encoding="utf-8") as f:
    places = json.load(f)

for p in places:
    coords = p["coords"]
    best_dist = None
    min_d = float("inf")
    for d in districts:
        dist = get_dist(coords, d["coords"])
        if dist < min_d:
            min_d = dist
            best_dist = d
    if best_dist:
        p["region"] = f"{best_dist['name']}, {best_dist['oblast']}"

with open(tauri_places, "w", encoding="utf-8") as f:
    json.dump(places, f, ensure_ascii=False, indent=None)

with open(public_places, "w", encoding="utf-8") as f:
    json.dump(places, f, ensure_ascii=False, indent=None)

